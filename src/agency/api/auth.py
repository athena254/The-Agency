"""Bearer-token authentication for the enabled HTTP intake surface.

Owner-issued tokens let registered callers — humans and external agents —
submit tasks and read their own results without opening the peer-grant path
(SPEC sequencing keeps Ed25519 ``ExecutionGrant`` actuation behind the
consensus foundation, D6/D8). This module reuses the sanctioned
``OwnerAuthenticator`` pattern: constant-time comparison, explicit
provisioning, and fail-closed behaviour.

Fail-closed rules
-----------------
* No ``AGENCY_API_TOKENS`` file configured  -> every authed route 503s, and
  the middleware keeps denying everything else exactly as before.
* Missing/malformed ``Authorization`` header or unknown token -> 401.
* Token valid but missing a required scope  -> 403.

Token file format (``AGENCY_API_TOKENS`` points to a JSON file)::

    [
      {"token": "sk-...", "caller_id": "danny", "role": "owner"},
      {"token": "sk-...", "caller_id": "agent-coder-1", "role": "agent"}
    ]

``role`` selects the default scope set; an explicit ``scopes`` list may only
narrow it. Tokens are generated by the operator (e.g.
``python -c "import secrets; print(secrets.token_urlsafe(48))"``) and the
file should be ACL-protected like ``owner.token``.
"""

from __future__ import annotations

import json
import os
import secrets
from dataclasses import dataclass
from typing import Final

import structlog
from fastapi import HTTPException, Request, status

log = structlog.get_logger(__name__)

TOKENS_ENV_VAR: Final = "AGENCY_API_TOKENS"
_MIN_TOKEN_CHARS: Final = 24

KNOWN_SCOPES: Final[frozenset[str]] = frozenset(
    {"tasks:write", "tasks:read", "chat:send", "tasks:admin"}
)

ROLE_SCOPES: Final[dict[str, frozenset[str]]] = {
    "owner": frozenset({"tasks:write", "tasks:read", "tasks:admin", "chat:send"}),
    "human": frozenset({"tasks:write", "tasks:read", "chat:send"}),
    "agent": frozenset({"tasks:write", "tasks:read", "chat:send"}),
}


@dataclass(frozen=True)
class Principal:
    """An authenticated caller bound to the token, not to client input."""

    caller_id: str
    role: str
    scopes: frozenset[str]

    def has_scopes(self, *required: str) -> bool:
        return all(scope in self.scopes for scope in required)


class TokenRegistry:
    """In-memory index of owner-issued bearer tokens (constant-time lookup)."""

    def __init__(self, entries: list[tuple[str, Principal]]) -> None:
        self._tokens: list[tuple[str, Principal]] = entries

    @classmethod
    def from_env(cls, env_var: str = TOKENS_ENV_VAR) -> TokenRegistry | None:
        """Load the registry from ``env_var``; ``None`` when unset/blank."""

        path = os.environ.get(env_var, "").strip()
        if not path:
            return None
        return cls.load(path)

    @classmethod
    def load(cls, path: str) -> TokenRegistry:
        """Parse the token file. Raises ``ValueError`` on malformed entries."""

        with open(path, encoding="utf-8") as handle:
            raw = json.load(handle)
        if not isinstance(raw, list):
            raise ValueError(f"{path}: token file must be a JSON array")
        entries: list[tuple[str, Principal]] = []
        seen: set[str] = set()
        for index, item in enumerate(raw):
            if not isinstance(item, dict):
                raise ValueError(f"{path}: entry {index} must be an object")
            token = item.get("token")
            caller_id = item.get("caller_id")
            role = item.get("role")
            if not isinstance(token, str) or len(token) < _MIN_TOKEN_CHARS:
                raise ValueError(f"{path}: entry {index} token missing/short")
            if not isinstance(caller_id, str) or not caller_id.strip():
                raise ValueError(f"{path}: entry {index} caller_id missing")
            if role not in ROLE_SCOPES:
                raise ValueError(f"{path}: entry {index} unknown role {role!r}")
            if token in seen:
                raise ValueError(f"{path}: entry {index} duplicate token")
            seen.add(token)
            scopes = ROLE_SCOPES[role]
            custom = item.get("scopes")
            if custom is not None:
                if (
                    not isinstance(custom, list)
                    or not custom
                    or not all(isinstance(s, str) and s in KNOWN_SCOPES for s in custom)
                ):
                    raise ValueError(f"{path}: entry {index} invalid scopes")
                scopes = frozenset(custom) & ROLE_SCOPES[role]
            entries.append((token, Principal(caller_id.strip(), role, scopes)))
        log.info(
            "api.auth.tokens_loaded",
            path=path,
            callers=len(entries),
        )
        log.warning(
            "api.auth.transport_warning",
            detail="bearer tokens are plaintext over HTTP; bind to loopback or terminate TLS",
        )
        return cls(entries)

    def authenticate(self, authorization: str | None) -> Principal:
        """Resolve a caller from the ``Authorization`` header. Fail-closed.

        Raises
        ------
        HTTPException
            503 when this registry is empty (no tokens configured), 401 on a
            missing or unknown credential.
        """

        if not self._tokens:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Peer authorization is unavailable.",
            )
        presented = _bearer_token(authorization)
        if presented is not None:
            for token, principal in self._tokens:
                if secrets.compare_digest(presented, token):
                    return principal
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or missing bearer token.",
            headers={"WWW-Authenticate": "Bearer"},
        )


def _bearer_token(authorization: str | None) -> str | None:
    """Extract the token from a ``Bearer <token>`` header value, else ``None``."""

    if not isinstance(authorization, str):
        return None
    scheme, _, token = authorization.partition(" ")
    if scheme.lower() != "bearer" or not token.strip():
        return None
    return token.strip()


async def require_principal(request: Request, *required_scopes: str) -> Principal:
    """FastAPI dependency: authenticate the caller and enforce scopes.

    The registry lives on ``app.state.token_registry``; when absent (no
    token file configured) every authed route fails closed with 503.
    """

    registry = getattr(request.app.state, "token_registry", None)
    if registry is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Peer authorization is unavailable.",
        )
    principal = registry.authenticate(request.headers.get("authorization"))
    missing = next((s for s in required_scopes if not principal.has_scopes(s)), None)
    if missing is not None:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail=f"token lacks required scope: {missing}",
        )
    request.state.principal = principal
    return principal


def principal_dependency(*required_scopes: str):  # type: ignore[no-untyped-def]
    """Bind ``require_principal`` with fixed scopes for a route."""

    async def dependency(request: Request) -> Principal:
        return await require_principal(request, *required_scopes)

    return dependency
